#!/usr/bin/env bash
set -euo pipefail

BUILD_DIR="${1:-build/macos}"
DIST_DIR="${2:-dist}"
VERSION="${3:-0.2.0}"

mkdir -p "$DIST_DIR"

APP_PATH="$BUILD_DIR/app/Whale Mix.app"
if [ ! -d "$APP_PATH" ]; then
    APP_PATH="$BUILD_DIR/Whale Mix.app"
fi

if [ ! -d "$APP_PATH" ]; then
    echo "Error: Whale Mix.app not found in $BUILD_DIR"
    exit 1
fi

if [ -d "samples" ]; then
    mkdir -p "$APP_PATH/Contents/Resources"
    cp -R samples "$APP_PATH/Contents/Resources/"
fi

echo "Deploying $APP_PATH into DMG..."
macdeployqt "$APP_PATH" -dmg

# Find generated dmg and rename
DMG_GENERATED="$(find "$BUILD_DIR" -name "*.dmg" | head -n 1)"
if [ -n "$DMG_GENERATED" ]; then
    mv "$DMG_GENERATED" "$DIST_DIR/WhaleMix-${VERSION}-macos.dmg"
    echo "Successfully created $DIST_DIR/WhaleMix-${VERSION}-macos.dmg"
else
    echo "Error: DMG was not generated by macdeployqt"
    exit 1
fi
